from typing import Protocol, List, Optional, Any, Dict
from pydantic import BaseModel, Field


class Message(BaseModel):
    role: str = Field(description="Role of the speaker: system, user, assistant")
    content: str = Field(description="Message text content")


class LLMResult(BaseModel):
    text: str = Field(description="Raw text generated by LLM")
    parsed: Optional[Dict[str, Any]] = Field(default=None, description="Parsed structured data if schema provided")
    latency_ms: int = Field(default=0, description="Execution time in milliseconds")
    token_usage: Dict[str, int] = Field(default_factory=dict, description="Input and output token count")


class LLMProviderError(Exception):
    """Raised when an LLM provider fails or exceeds retry limit."""
    pass


class LLMProvider(Protocol):
    """Abstract interface for LLM calls (PROJECT.md §7).
    No agent or service directly imports vendor SDKs.
    """
    async def complete(
        self,
        messages: List[Message],
        *,
        json_schema: Optional[Dict[str, Any]] = None,
        temperature: float = 0.2,
        max_tokens: Optional[int] = None,
    ) -> LLMResult:
        ...
